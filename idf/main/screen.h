/*
 * Содержимое экрана прибора — ДВЕ страницы (макет v5, docs/screens-v5.md):
 *
 *   0 СВОДНЫЙ — то, за чем прибор и стоит: свежие ли данные, температуры двух GPU
 *               (самое крупное на экране), загрузка CPU/RAM/DISK, аптайм хоста,
 *               датчик на плате;
 *   1 SETUP   — то, что кнопками не набрать и что нужно, когда прибор ведёт себя
 *               странно: адрес веб-кабинета, поворот экрана, режим диска, цель пинга,
 *               подсказки по кнопкам, версия прошивки и аптайм прибора.
 *
 * Переключаются коротким нажатием PWR: сводный → SETUP → сводный.
 *
 * Шрифты (см. display.h): подписи 6x11, проценты 18x30, заголовки и значения 12x22,
 * температуры 40x48. Крупнее температуры не сделать: две цифры плюс «°» на две
 * половины экрана дают 192 px из 200.
 *
 * Про «н/д»: если поле агент не прислал, на экране прочерк `--`, а не ноль. Ноль и
 * «неизвестно» — разные вещи, и по экрану это должно быть видно.
 */
#ifndef SCREEN_H
#define SCREEN_H

#include <stdbool.h>
#include <stdint.h>

#define SCREEN_PAGES      2
#define SCREEN_GPU_MAX    2      /* сколько карт показываем */
#define SCREEN_NEVER      0xFFFFFFFFu

/* Данные агента старше этого — «нет связи»: агент шлёт раз в минуту, один
   пропущенный кадр ещё не авария, два подряд — уже повод показать это на экране.
   Значение держать равным INGEST_STALE_S (idf/main/ingest.h). */
#define SCREEN_ONLINE_S   90

typedef struct {
    /* --- связь с хостом (агент метрик, POST /ingest) --- */
    bool        agent_have;        /* данные от агента вообще были */
    bool        agent_ok;          /* возраст не больше SCREEN_ONLINE_S — метрикам верим */
    uint32_t    agent_age_s;       /* сколько секунд с последнего приёма */

    /* --- состояние ХОСТА по интернету: это и показывает рамка ---
       ONLINE  — агент на связи И хост дотянулся до цели пинга (у хоста есть интернет);
       OFFLINE — агент на связи, но интернет у хоста не отвечает;
       NO DATA — агент молчит (метрики старше SCREEN_ONLINE_S): про интернет хоста
                 прибор ничего не знает, и делать вид, что знает, не должен. */
    bool        host_online;
    bool        host_net_known;     /* хост сообщил результат проверки интернета */
    uint32_t    host_ping_ms;       /* задержка пинга с хоста, мс */
    const char *host_ping_target;   /* что хост пинговал (8.8.8.8, ya.ru) */

    /* --- метрики хоста --- */
    float       cpu_pct, mem_pct, disk_pct;   /* % загрузки; отрицательное — «н/д» */
    int         gpu_count;                    /* сколько карт реально есть (0, 1, 2) */
    int         gpu_temp_c[SCREEN_GPU_MAX];   /* температуры, °C; -1 — «н/д» */
    float       gpu_pct[SCREEN_GPU_MAX];      /* загрузка карт, %; -1 — «н/д» */
    bool        hup_ok;                       /* аптайм хоста известен */
    float       hup_h;                        /* аптайм хоста, часы */

    /* --- датчик на плате (SHTC3) --- */
    bool        sensor_ok;
    float       t_c;
    float       rh;

    /* --- прибор --- */
    const char *dev_ip;            /* адрес веб-кабинета, он же адрес прибора */
    uint32_t    up_s;              /* аптайм прибора, с */
    const char *fw;                /* версия прошивки */

    /* --- настройки, которые показывает экран SETUP --- */
    const char *ping_target;       /* цель пинга (YA.RU и т.п.) */
    uint16_t    rotation;          /* 0 / 90 / 180 / 270 */
    bool        disk_write_lock;   /* диск прибора только для чтения */

    /* аварийное состояние: инверсный вид + полное обновление */
    bool        emergency;
} screen_state_t;

void screen_show(const screen_state_t *st, int page);

#endif /* SCREEN_H */
