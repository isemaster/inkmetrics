/* Чёрный ящик логов: см. diag.c */
#pragma once

#include <stdint.h>

#include "esp_err.h"

/*
 * Адрес и размер области берутся из partitions.csv (раздел `diag`), но пишем мы
 * НЕ через API разделов, а по абсолютному адресу: если таблица разделов в прошивке
 * и на флеше разойдутся, `esp_partition_find_first()` вернёт NULL и «чёрный ящик»
 * молча перестанет писать — так уже было (раздел оказался пустым, а прошивка при
 * этом не падала). Запись по адресу — без посредников.
 */
#define DIAG_FLASH_ADDR 0x7E0000u
#define DIAG_FLASH_SIZE (16 * 1024)

/* Первым делом в app_main: стереть область, записать заголовок и метку старта. */
esp_err_t diag_init(const char *fw_version);

/* Метка стадии: строка сразу уходит во флеш (видно, до чего дошла прошивка). */
void diag_step(const char *fmt, ...);

/* Пишется потоком, буфера нет — оставлено для совместимости. */
void diag_flush(void);
